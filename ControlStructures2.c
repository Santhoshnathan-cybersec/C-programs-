#include<stdio.h>
int main(){
	int a=10;
	if(a<10) //Condition that tells whether the a is less than 10 or not 
	{
		printf("The A is less than 10 ");//If yes this condition will be executed 
	}
	else//IN our example this exceeds the if and jumps to the else statement 
	{
		printf("The A is not less than 10\n");
	}
}