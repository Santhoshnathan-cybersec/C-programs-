/*This c program demonstrates about the  Arthematic operator  */
#include <stdio.h>
int main(){
    int a=10,b=2; 
    printf("The sum of a and b is :%d\n",a+b);//Addition
    printf("The difference between a and b is : %d\n",a-b);//Subtraction
    printf("The product of a and b is : %d\n",a*b);//Multiplication
    printf("The quotient of a and b is : %d\n",a/b);//Division
    printf("The remainder of a and b is : %d\n",a%b);//Modulus
    return 0;
}