#include<stdio.h>
int main()
{
        int A=03;//Integer data type
        float a=1.2;//Float data type
        char s='A';//Character data type
        char str[50]="Hello this program tells about data types";//String data type
        printf("This is an integer %d\n", A);//%d is a format specifier for integer
        printf("This is a float %f\n", a);//%f is a format specifier for float
        printf("This is a character %c\n", s);//%c is a format specifier for character
        printf("This is a string %s\n", str);//%s is a format specifier for string
}